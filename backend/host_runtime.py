@runtime_checkable
class WorkRuntime(Protocol):
    """Process-owned durable work service lifecycle.

    Domain-specific APIs remain on the concrete service facets.  Host
    composition depends only on lifecycle so the Work Fabric can evolve
    without turning ``HostRuntime`` into a callback registry.
    """

    async def start(self) -> None: ...
    async def shutdown(self) -> None: ...
    def record_capability_receipt(self, receipt: Any) -> None: ...


