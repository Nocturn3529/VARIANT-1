"""Typed runtime services installed once on :class:`app_host.AppHost`.

The runtime is a late-bound composition boundary because many VARIANT-1 services
refer back to ports built by ``AppHost``.  It is deliberately *not* a callback
registry: each field is a concrete service implementing an explicit protocol
with stable method signatures.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Callable, Protocol, runtime_checkable


StopPredicate = Callable[[], bool]


@runtime_checkable
class ChatRuntime(Protocol):
    async def handle_chat(
        self, websocket: Any, text: str, session: Any, *, resume: bool = False,
        reserved: bool = False, client_id: str = "", source: str = "",
        images: list[dict] | None = None, attachment_text: str = "",
    ) -> None: ...
    def build_task_turn_ports(self, websocket: Any, session: Any) -> Any: ...
    async def extract_and_store(
        self, user_text: str, reply: str, *, evidence: dict | None = None,
    ) -> None: ...
    async def remember_explicit(
        self, text: str, *, session_id: str = "",
    ) -> bool: ...
    async def compress_messages(
        self, messages: list, protect_first: int = 2, protect_last: int = 6,
        should_stop: StopPredicate | None = None,
    ) -> list: ...
    def approx_tokens(self, messages: list) -> int: ...
    def ctx_compress_threshold(self) -> int: ...
    async def count_prompt_tokens(
        self, messages: list, *, tools: list | None = None, image_b64=None,
    ) -> int | None: ...
    def prompt_context(
        self, memories: list, attachment_context: str = "",
    ) -> Any: ...
    def vision_state(self) -> tuple[bool, str]: ...
    def build_system_prompt(
        self, memories: list, attachment_context: str = "",
    ) -> str: ...
    def build_internal_system_prompt(
        self, memories: list, attachment_context: str = "",
    ) -> str: ...
    def snapshot_resume_state(self, chat_id: str = "") -> tuple[Any, str]: ...
    def snapshot_follow_up_state(self, chat_id: str = "") -> tuple[Any, str]: ...
    async def accept_follow_up_evidence(self, chat_id: str, candidate: Any) -> Any: ...
    def orphaned_task_payload(self, chat_id: str = '') -> dict | None: ...
    def sessions_message(self) -> dict: ...
    def viewed_session_id(self, session: Any) -> str: ...
    async def run_task(
        self, websocket: Any, text: str, session: Any, *, resume: bool = False,
        turn_seq: Any = None, client_id: str = "", source: str = "",
        images: list[dict] | None = None, attachment_text: str = "",
        runtime_admission_id: str = "", ticket_id: str = "",
    ) -> None: ...


