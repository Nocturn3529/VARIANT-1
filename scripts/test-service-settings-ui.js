"use strict";
const assert = require("node:assert/strict"), path = require("node:path"), Module = require("node:module");
const {buildSync} = require("esbuild"), {JSDOM} = require("jsdom");
const root = path.resolve(__dirname, "..");
const dom = new JSDOM('<div id="root"></div>', {url: "http://localhost"});
global.window = dom.window; global.document = dom.window.document;
Object.defineProperty(global, "navigator", {value: dom.window.navigator, configurable: true});
global.IS_REACT_ACT_ENVIRONMENT = true;
const React = require("react"), {createRoot} = require("react-dom/client");
const output = buildSync({stdin: {contents: 'export * from "./serviceSettingsStore"; export * from "./ToolsAndKeysSettings";', resolveDir: path.join(root, "frontend/main-deck/src"), loader: "ts"},
  bundle: true, platform: "node", format: "cjs", jsx: "automatic", external: ["react", "react-dom"], write: false, logLevel: "silent"}).outputFiles[0].text;
const compiled = new Module(__filename + ".bundle", module); compiled.filename = __filename; compiled.paths = module.paths; compiled._compile(output, __filename);
const api = compiled.exports, sent = [];
const row = {id: "models:huggingface", service: "models", provider: "huggingface", name: "Hugging Face", group: "Model downloads", settings_category: "local-models", editable: true, configured: false, stored: false, source: "", revision: "v1"};
const last = operation => sent.filter(item => item.type === `service-settings:${operation}`).at(-1);
function reply(request, result, error) {api.ingestServiceSettings({type: "service-settings:result", operation: request.type.split(":")[1], request_id: request.request_id, ok: !error, result, error: error ? {message: error} : undefined});}
const click = text => React.act(() => [...document.querySelectorAll("button")].find(button => button.textContent === text).click());
api.setServiceSettingsContext({send: payload => {sent.push(payload); return true;}});
assert.equal(api.refreshServiceSettings(), false);
api.setServiceSettingsConnection("connected");
const mount = createRoot(document.getElementById("root"));
React.act(() => mount.render(React.createElement(api.ToolsAndKeysSettings)));
React.act(() => reply(last("get"), {items: [row, {...row, id: "web:variant1", name: "VARIANT-1 Search", group: "Search", editable: false}]}));
assert.equal(document.querySelectorAll('input[type="password"]').length, 1, "keyless service has no inert key editor");
const input = document.querySelector('input[type="password"]');
React.act(() => {
  Object.getOwnPropertyDescriptor(dom.window.HTMLInputElement.prototype, "value").set.call(input, "secret-fixture");
  input.dispatchEvent(new dom.window.Event("input", {bubbles: true}));
});
React.act(() => {api.refreshServiceSettings(); reply(last("get"), {items: [{...row, revision: "v2", stored: true}]} );});
assert.ok([...document.querySelectorAll("button")].some(button => button.textContent === "Use refreshed setting"));
click("Save"); const stale = last("set"); assert.equal(stale.expected_revision, "v1", "draft keeps its original revision until reviewed");
React.act(() => reply(stale, null, "Refresh before saving."));
assert.equal(input.value, "secret-fixture", "rejected save keeps draft");
click("Use refreshed setting"); click("Save");
const save = last("set"); assert.equal(save.expected_revision, "v2");
React.act(() => api.refreshServiceSettings()); const preMutation = last("get");
React.act(() => reply(save, {item: {...row, revision: "v3", configured: true, stored: true, source: "stored"}}));
assert.equal(input.value, "");
assert.equal(JSON.stringify(api.getServiceSettings()).includes("secret-fixture"), false, "secret is not retained in shared state");
React.act(() => reply(preMutation, {items: [row]}));
assert.equal(api.getServiceSettings().items[0].revision, "v3", "older inventory cannot undo acknowledged credential state");
dom.window.confirm = () => true; click("Remove"); assert.equal(last("clear").provider, "huggingface");
const pendingClear = last("clear");
React.act(() => api.setServiceSettingsConnection("offline"));
React.act(() => reply(pendingClear, {item: row}));
assert.equal(api.getServiceSettings().items[0].revision, "v3", "disconnected reply cannot settle a newer view");
React.act(() => mount.unmount()); dom.window.close();
console.log("Tools & Keys UI: live catalog, masked input, revision review, draft retention, owned receipts and disconnect fences passed");
